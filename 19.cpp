#include <iostream>
// Write a program to reverse a given number (e.g., 12345 → 54321). 
using namespace std;
int main() {
        cout<<"*** program to reverse the number ***"<<endl;

    for(int i=1;i<=10;i++){
        cout<<i<<"\t";
    }

    cout<<"\n The reverse string is : "<<endl;
    for(int i=10;i>=1;i--){
        cout<<i<<"\t";
    }
    return 0;
}